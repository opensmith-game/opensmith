"""The demo song shipped with the app, to play without any music file of one's own.

Bass and drums of the synthetic band (`synth.rock_song`) as the backing track, and the guitar
part charted from the very notes it was made of. Everything is generated by this code: no
recording, nothing to license.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from . import audio_io, synth
from .builder import BeatGrid, build_chart
from .chart import Chart

TITLE = "First Riff"
ARTIST = "OpenSmith"
ALBUM = "Demo"
# Mono at 32 kHz: bass and drums only, a light file to keep in the repository.
RATE = 32_000
BACKING = "backing.wav"


def make_demo(out_dir: Path, *, bars: int = 16, bpm: float = 100.0, seed: int = 7) -> Chart:
    """Writes the demo song (`song_chart.json`, `backing.wav`) into `out_dir`."""
    song = synth.rock_song(sr=RATE, bpm=bpm, bars=bars, seed=seed)
    lead_in = song.beats[0]
    grid = BeatGrid.regular(bpm, song.duration, start=lead_in)
    chart = build_chart(
        song.guitar_notes,
        grid,
        title=TITLE,
        artist=ARTIST,
        duration=song.duration,
        source_kind="synth",
        source_file="opensmith-ingest demo",
        consensus=False,
    )
    chart.album = ALBUM
    out_dir.mkdir(parents=True, exist_ok=True)
    backing = song.backing.mean(axis=0)
    audio_io.write_wav(out_dir / BACKING, backing / max(float(np.abs(backing).max()) / 0.9, 1e-9), RATE, pcm16=True)
    chart.audio_backing = BACKING
    chart.save(out_dir / "song_chart.json")
    return chart
